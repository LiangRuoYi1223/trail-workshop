import { app, BrowserWindow, ipcMain, protocol, utilityProcess } from 'electron';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { mkdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { writeArrayBuffer } from 'geotiff';
import { createDesktopManager } from '../main/manager.mjs';
import { createSessionStore } from '../main/session.mjs';

const root = fileURLToPath(new URL('../../',import.meta.url));
const output = join(root,'artifacts','color-print-check');
mkdirSync(output,{recursive:true});
app.setPath('userData',join(output,`profile-${Date.now()}`));
app.disableHardwareAcceleration();
protocol.registerSchemesAsPrivileged([{scheme:'terrain-map',privileges:{standard:true,secure:true}}]);
const delay = ms => new Promise(resolve=>setTimeout(resolve,ms));
let window,manager,session;
let lastJob,lastImage,saved;
const exports = [];
const errors = [];
async function run() {
  await app.whenReady();
  protocol.handle('terrain-map',()=>new Response(null,{status:404}));
  const routePath = join(output,'彩色 路线.KML');
  const imagePath = join(output,'地表 分类.tif');
  await writeFile(routePath,'<kml xmlns="http://www.opengis.net/kml/2.2"><Document><name>三色验证路线</name><Placemark><LineString><coordinates>104.28,30.56 104.29,30.565 104.30,30.57</coordinates></LineString></Placemark></Document></kml>');
  const pixels = new Uint8Array(32*32*3);
  for(let y=0;y<32;y++)for(let x=0;x<32;x++)pixels.set(x<16?[60,140,50]:[145,142,138],(y*32+x)*3);
  const image = writeArrayBuffer(pixels,{width:32,height:32,SamplesPerPixel:3,BitsPerSample:[8,8,8],SampleFormat:[1,1,1],PhotometricInterpretation:2,PlanarConfiguration:1,
    GeographicTypeGeoKey:4326,GTModelTypeGeoKey:2,GTRasterTypeGeoKey:1,ModelPixelScale:[.08/32,.08/32,0],ModelTiepoint:[0,0,0,104.25,30.61,0]});
  await writeFile(imagePath,Buffer.from(image));
  manager = createDesktopManager({taskRoot:join(output,'tasks'),coreModuleUrl:pathToFileURL(join(root,'dist/src/index.js')).href,
    workerFactory:({workerPath,taskDir})=>utilityProcess.fork(workerPath,[],{cwd:taskDir,stdio:'pipe'}),
    onJob:job=>{lastJob=job;window?.webContents.send('terrain:job',job);}});
  session=createSessionStore({userDataDirectory:app.getPath('userData'),manager});
  const handle=(name,operation)=>ipcMain.handle(`terrain:${name}`,async(_event,...args)=>{try{return{ok:true,value:await operation(...args)};}catch(error){return{ok:false,error:{code:error.code??'TEST',message:error.message}};}});
  handle('runtime',()=>({version:'0.4.0',platform:'win32',packaged:false,units:'mm'}));
  handle('cache-info',()=>({path:output,elevationBytes:0,mapBytes:0}));
  handle('session-get',()=>session.getSession());handle('session-save',request=>session.saveSession(request));handle('session-restore',()=>session.restoreSession());
  handle('choose-route',()=>manager.addRoute(routePath));handle('choose-dem',()=>manager.addDem(join(root,'data','copernicus-longquanshan.tif')));
  handle('choose-image',async()=>lastImage=await manager.addImage(imagePath));handle('remove-image',id=>manager.removeImage(id));
  handle('import-image',async path=>lastImage=await manager.addImage(path));
  handle('inspect',request=>manager.inspect(request));handle('start',request=>manager.start(request));
  handle('get',id=>manager.get(id));handle('preview',id=>manager.preview(id));handle('cancel',id=>manager.cancel(id));
  handle('save-model',async request=>{
    const artifact=await manager.exportModel(request.id,request.format,request.options);
    const {saveModelFile}=await import('../main/save-model.mjs');
    const source=artifact.format==='stl'?await manager.artifact(request.id):undefined;
    saved=await saveModelFile(artifact.bytes,join(output,`导出-${exports.length+1}.${artifact.extension.replace(/^\./,'')}`),{overwriteApproved:true,...(source?{sourcePath:source.path,expectedSha256:source.stlSha256}:{})});
    exports.push({format:request.format,appearanceHash:artifact.appearanceHash,...saved});
    return{cancelled:false,...saved};
  });
  window=new BrowserWindow({show:false,width:1280,height:1000,webPreferences:{preload:join(root,'desktop/main/preload.cjs'),contextIsolation:true,nodeIntegration:false,sandbox:true,backgroundThrottling:false,offscreen:true}});
  window.webContents.on('console-message',event=>{if(event.level==='error'&&!event.message.includes('terrain-map'))errors.push(event.message);});
  await window.loadFile(join(root,'desktop/dist/renderer/index.html'));
  const js=async source=>{try{return await window.webContents.executeJavaScript(source);}catch(error){throw new Error(`${error.message}\nRenderer operation: ${source}\nConsole: ${JSON.stringify(errors)}`,{cause:error});}};
  const wait=async(predicate,label)=>{const until=Date.now()+45000;while(Date.now()<until){if(await predicate())return;await delay(50);}throw Error(`Timed out: ${label}; ${await js("document.querySelector('.task-error')?.textContent??''")}`);};
  const ready=label=>js(`[...document.querySelectorAll('button')].some(el=>el.textContent===${JSON.stringify(label)}&&!el.disabled)`);
  const click=label=>js(`(()=>{const el=[...document.querySelectorAll('button')].find(el=>el.textContent===${JSON.stringify(label)});if(!el||el.disabled)throw Error('Button unavailable: '+${JSON.stringify(label)});el.click();})()`);
  const select=(selector,value)=>js(`(()=>{const el=document.querySelector(${JSON.stringify(selector)});if(!el)throw Error('Select missing');const setter=Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set;setter.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  const input=(selector,value)=>js(`(()=>{const el=document.querySelector(${JSON.stringify(selector)});if(!el)throw Error('Input missing');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  const capture=async name=>{await wait(()=>js("!!document.querySelector('.terrain-canvas canvas')"),'three-dimensional canvas');await delay(700);await writeFile(join(output,name),(await window.webContents.capturePage()).toPNG());};
  await wait(()=>ready('导入路线'),'startup');
  await select('#image-mode','local');
  assert.equal(await ready('选择地表影像'),true,'missing real surface imagery import');
  await click('导入路线');
  await wait(()=>js("!!document.querySelector('.route-file strong') || [...document.querySelectorAll('button')].some(el=>el.textContent==='更换路线')"),'route imported');
  await select('.dem-mode select','local');await wait(()=>ready('选择高程'),'local elevation selected');
  await click('选择高程');await wait(()=>ready('选择地表影像'),'elevation imported');await click('选择地表影像');
  await wait(()=>!!lastImage&&ready('生成模型'),'image imported and model ready');
  await click('生成模型');await wait(()=>lastJob&&!['running','cancelling'].includes(lastJob.state),'generation');
  assert.equal(lastJob.state,'succeeded',lastJob.error?.message);
  await wait(()=>ready('保存彩色 3MF'),'verified color preview');
  const preview=await manager.preview(lastJob.id);
  assert.equal(preview.appearance.classification,'rgb-greenness');
  assert.deepEqual(new Set(preview.appearance.faceClasses),new Set(['grass','rock','route']));
  assert.equal(preview.appearance.palette.length,3);
  await capture('01-three-class-model.png');
  const modelId=lastJob.id;
  await click('保存彩色 3MF');await wait(()=>exports.length===1&&ready('保存彩色 3MF'),'first color save');
  assert.ok(await js("document.querySelector('.saved-path')?.textContent"));
  await input('#grass-color','#005522');await delay(100);
  assert.equal(await js("!!document.querySelector('.saved-path')"),false,'color edit must clear previous saved confirmation');
  assert.equal(await ready('保存彩色 3MF'),true,'color edit must not rebuild geometry');
  await click('保存彩色 3MF');await wait(()=>exports.length===2&&ready('保存彩色 3MF'),'updated colors saved');
  assert.notEqual(exports[0].sha256,exports[1].sha256);
  assert.notEqual(exports[0].appearanceHash,exports[1].appearanceHash);
  assert.equal(lastJob.id,modelId);
  await select('#print-colors','2');await select('#export-format','obj');await click('保存 OBJ 包');
  await wait(()=>exports.length===3&&ready('保存 OBJ 包'),'two-color obj save');
  const twoColor=await manager.exportModel(modelId,'3mf',{maxColors:2,grassColor:'#005522',rockColor:'#a9aa92',routeColor:'#c84832'});
  await writeFile(join(output,'两色验证.3mf'),twoColor.bytes);
  assert.match(await js("document.querySelector('.print-color-count').textContent"),/2/);
  await capture('02-two-color-model.png');
  await select('#export-format','stl');await click('保存 STL');await wait(()=>exports.length===4&&ready('保存 STL'),'stl compatibility');
  assert.equal(exports[3].sha256,lastJob.result.stlSha256);
  const reloaded=new Promise(resolve=>window.webContents.once('did-finish-load',resolve));window.reload();await reloaded;
  await wait(()=>ready('恢复上次项目'),'renderer reload recovery');await click('恢复上次项目');
  await wait(async()=>!!await js("document.querySelector('.image-detail')")&&ready('生成模型'),'image source recovered');
  assert.equal(await ready('保存彩色 3MF'),false,'recovery must not recreate an old model');
  assert.deepEqual(errors,[]);
  await writeFile(join(output,'result.json'),JSON.stringify({passed:true,threeClasses:true,maxThreeColors:true,twoColorMode:true,recolorWithoutRebuilding:true,colorSaveInvalidated:true,imageRecovery:true,stlPreserved:true,exports,validation:preview.report.validation,errors},null,2));
}
run().then(async()=>{await session?.close();await manager?.close();window?.destroy();app.exit(0);}).catch(async error=>{
  console.error(error);await mkdir(output,{recursive:true});await writeFile(join(output,'failure.txt'),error.stack??String(error));
  if(window&&!window.isDestroyed())await writeFile(join(output,'failure.png'),(await window.webContents.capturePage()).toPNG());
  await session?.close();await manager?.close();window?.destroy();app.exit(1);
});
