import { app, BrowserWindow, ipcMain, protocol, utilityProcess } from 'electron';
import { mkdir, writeFile } from 'node:fs/promises';
import { mkdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { createDesktopManager } from '../main/manager.mjs';
import { createSessionStore } from '../main/session.mjs';
const root=fileURLToPath(new URL('../../',import.meta.url));
const output=join(root,'artifacts','route-style-check');
mkdirSync(output,{recursive:true});
app.setPath('userData',join(output,'profile-'+Date.now()));
app.disableHardwareAcceleration();
protocol.registerSchemesAsPrivileged([{scheme:'terrain-map',privileges:{standard:true,secure:true}}]);
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
let window,manager;
const errors=[];
async function run() {
  await app.whenReady();
  protocol.handle('terrain-map',()=>new Response(null,{status:404}));
  let savedOptions,lastInspection,lastJob;
  manager=createDesktopManager({taskRoot:join(output,'tasks'),coreModuleUrl:pathToFileURL(join(root,'dist/src/index.js')).href,
    workerFactory:({workerPath,taskDir})=>utilityProcess.fork(workerPath,[],{cwd:taskDir,stdio:'pipe'}),
    onJob:job=>{lastJob=job;window?.webContents.send('terrain:job',job);} });
  const session=createSessionStore({userDataDirectory:app.getPath('userData'),manager});
  const handle=(name,fn)=>ipcMain.handle(`terrain:${name}`,async(_event,...args)=>{try{return{ok:true,value:await fn(...args)};}catch(error){return{ok:false,error:{code:error.code||'TEST',message:error.message}};}});
  handle('runtime',()=>({version:'0.3.5',platform:'win32',packaged:false,units:'mm'}));
  handle('cache-info',()=>({path:output,elevationBytes:0,mapBytes:0}));
  handle('session-get',()=>session.getSession());
  handle('session-save',request=>{savedOptions=request.options;return session.saveSession(request);});
  handle('session-restore',()=>session.restoreSession());
  handle('sample',async()=>({route:await manager.addRoute(join(root,'fixtures/sample-trail.gpx'),{isSample:true}),
    dem:await manager.addDem(join(root,'data/copernicus-longquanshan.tif'),{isSample:true})}));
  handle('inspect',async request=>{lastInspection=await manager.inspect(request);return lastInspection;});
  handle('start',request=>manager.start(request));handle('get',id=>manager.get(id));handle('preview',id=>manager.preview(id));
  handle('cancel',id=>manager.cancel(id));
  window=new BrowserWindow({show:false,width:1280,height:900,webPreferences:{preload:join(root,'desktop/main/preload.cjs'),contextIsolation:true,nodeIntegration:false,sandbox:true,backgroundThrottling:false}});
  window.webContents.on('console-message',event=>{if(event.level==='error'&&!event.message.includes('terrain-map')){errors.push(event.message);console.error(event.message);}});
  await window.loadFile(join(root,'desktop/dist/renderer/index.html'));
  const js=source=>window.webContents.executeJavaScript(source);
  const wait=async(predicate,label)=>{const until=Date.now()+30000;while(Date.now()<until){if(await predicate())return;await delay(50);}throw new Error(`Timed out: ${label}`);};
  const click=label=>js(`(()=>{const el=[...document.querySelectorAll('button')].find(el=>el.textContent===${JSON.stringify(label)});if(!el||el.disabled)throw Error('Button unavailable');el.click();})()`);
  const capture=async label=>writeFile(join(output,`${label}.png`),(await window.webContents.capturePage()).toPNG());
  const position=selector=>js(`(()=>{const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2};})()`);
  const drag=async(start,end)=>{
    window.webContents.sendInputEvent({type:'mouseMove',x:Math.round(start.x),y:Math.round(start.y)});
    window.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,x:Math.round(start.x),y:Math.round(start.y)});
    for(let i=1;i<=10;i++){await delay(20);window.webContents.sendInputEvent({type:'mouseMove',button:'left',x:Math.round(start.x+(end.x-start.x)*i/10),y:Math.round(start.y+(end.y-start.y)*i/10)});}
    window.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,x:Math.round(end.x),y:Math.round(end.y)});
  };
  const input = async (label, value) => {
    window.webContents.focus();
    await js(`(()=>{const el=[...document.querySelectorAll('input')].find(el=>el.getAttribute('aria-label')===${JSON.stringify(label)}||[...document.querySelectorAll('label')].some(l=>l.htmlFor===el.id&&l.textContent===${JSON.stringify(label)}));if(!el)throw Error('Input unavailable');el.scrollIntoView({block:'center'});el.focus();})()`);
    await delay(50);
    window.webContents.sendInputEvent({type:'keyDown',keyCode:'A',modifiers:['control']});
    await delay(25);
    window.webContents.sendInputEvent({type:'keyUp',keyCode:'A',modifiers:['control']});
    await delay(25);
    if(value==='') {window.webContents.sendInputEvent({type:'keyDown',keyCode:'Backspace'});window.webContents.sendInputEvent({type:'keyUp',keyCode:'Backspace'});}
    else await window.webContents.insertText(String(value));
    await delay(150);
  };
  const rgb = async (r,g,b) => { await input('路线颜色 R',r);await input('路线颜色 G',g);await input('路线颜色 B',b);await js('document.activeElement.blur()'); };
  const wheelClick = async (x,y) => {
    const point=await position('.color-wheel');
    window.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,x:Math.round(point.x+x*82),y:Math.round(point.y+y*82)});
    window.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,x:Math.round(point.x+x*82),y:Math.round(point.y+y*82)});
  };
  await wait(()=>js(`!document.querySelector('.sample-button').disabled`),'startup');
  await click('打开龙泉山示例');
  await wait(()=>lastInspection&&js(`!document.querySelector('.map-actions button').disabled`),'sample framing');
  await js(`document.querySelector('.map-basemap input').click();document.querySelector('.route-style-section').scrollIntoView({block:'center'});`);
  await rgb(255,0,0);
  await wait(()=>savedOptions.routeColor==='#ff0000','RGB red');
  assert.equal(await js(`document.querySelector('.leaflet-overlay-pane path').getAttribute('stroke')`),'#ff0000');
  assert.deepEqual(await js(`[...document.querySelectorAll('.rgb-field output')].map(el=>el.textContent)`),['100.0%','0.0%','0.0%']);
  await wheelClick(0,-1);
  await wait(()=>savedOptions.routeColor!=='#ff0000','wheel click changes hue');
  const picked=savedOptions.routeColor;
  const wheelCenter=await position('.color-wheel');
  await drag({x:wheelCenter.x+60,y:wheelCenter.y},{x:wheelCenter.x,y:wheelCenter.y+60});
  await wait(()=>savedOptions.routeColor!==picked,'continuous wheel drag');
  await js(`document.querySelector('.color-wheel').focus()`);
  const keyboardBefore=savedOptions.routeColor;
  window.webContents.sendInputEvent({type:'keyDown',keyCode:'Right'});window.webContents.sendInputEvent({type:'keyUp',keyCode:'Right'});
  await wait(()=>savedOptions.routeColor!==keyboardBefore,'keyboard wheel hue');
  const brightness=await position('.color-brightness input');
  window.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,x:Math.round(brightness.x),y:Math.round(brightness.y)});
  window.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,x:Math.round(brightness.x),y:Math.round(brightness.y)});
  await wait(()=>js(`Number(document.querySelector('.color-brightness input').value)<70`),'brightness slider');
  await rgb(0,128,255);
  await wait(()=>savedOptions.routeColor==='#0080ff','RGB blue');
  await input('路线颜色 R',256);
  assert.equal(await js(`document.querySelector('[aria-label="路线颜色 R"]').getAttribute('aria-invalid')`),'true');
  assert.equal(savedOptions.routeColor,'#0080ff');
  await js('document.activeElement.blur()');
  await wait(()=>js(`document.querySelector('[aria-label="路线颜色 R"]').value==='0'`),'invalid RGB recovers on blur');
  await input('路线宽度','');
  assert.equal(await js(`document.querySelector('.leaflet-overlay-pane path').getAttribute('stroke-width')`),'3','empty width must retain a visible route');
  await input('路线宽度',2.5);await input('凸起厚度',2.4);await js('document.activeElement.blur()');
  await wait(()=>savedOptions.routeWidthMm===2.5&&savedOptions.routeHeightMm===2.4,'width and thickness settings');
  assert.equal(await js(`document.querySelector('.leaflet-overlay-pane path').getAttribute('stroke-width')`),'7.5');
  await capture('01-map-style');
  window.setSize(960,720);await delay(150);
  await js(`document.querySelector('.route-color-picker').scrollIntoView({block:'center'});`);await capture('02-small-window');
  assert.equal(await js(`document.querySelector('.sidebar').scrollWidth<=document.querySelector('.sidebar').clientWidth`),true,'color fields overflow sidebar');
  await click('生成模型');
  await wait(()=>lastJob&&!['running','cancelling'].includes(lastJob.state),'generated model');
  assert.equal(lastJob.state,'succeeded',lastJob.error?.message);
  await wait(()=>js(`!!document.querySelector('.terrain-canvas canvas')`),'final preview');
  const preview=await manager.preview(lastJob.id);
  assert.equal(preview.report.integratedModel.route.heightMm,2.4);assert.equal(preview.report.integratedModel.route.widthMm,2.5);
  assert.equal(preview.report.validation.connectedComponents,1);assert.equal(preview.report.validation.boundaryEdges,0);
  const jobId=lastJob.id,stlHash=lastJob.result.stlSha256;
  await js('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');await capture('03-blue-model');
  const canvasBox=await js(`(()=>{const b=document.querySelector('.terrain-canvas canvas').getBoundingClientRect();return{x:Math.round(b.x),y:Math.round(b.y),width:Math.round(b.width),height:Math.round(b.height)};})()`);
  const blueCapture=await window.webContents.capturePage(canvasBox),bluePixels=blueCapture.toPNG();
  await rgb(255,0,0);
  await wait(()=>savedOptions.routeColor==='#ff0000','preview red');await delay(200);
  let redPixels;
  await wait(async()=>{redPixels=(await window.webContents.capturePage(canvasBox)).toPNG();return !bluePixels.equals(redPixels);},'3D canvas repaint after color edit');
  await writeFile(join(output,'blue-canvas.png'),bluePixels);await writeFile(join(output,'red-canvas.png'),redPixels);
  assert.equal(bluePixels.equals(redPixels),false,'3D canvas route color did not update');
  assert.equal(lastJob.id,jobId);assert.equal(lastJob.result.stlSha256,stlHash);
  assert.equal(await js(`[...document.querySelectorAll('button')].find(el=>el.textContent==='保存 STL').disabled`),false,'color edit invalidates STL');
  await capture('04-red-model');
  await input('凸起厚度',1.5);await js('document.activeElement.blur()');
  await wait(()=>savedOptions.routeHeightMm===1.5,'thickness edit');
  assert.equal(await js(`[...document.querySelectorAll('button')].find(el=>el.textContent==='保存 STL').disabled`),true,'thickness edit leaves old STL saveable');
  assert.equal(errors.length,0,errors.join('\n'));
  await session.close();
  const reopened=createSessionStore({userDataDirectory:app.getPath('userData'),manager});
  const restored=await reopened.getSession();
  assert.equal(restored.preferences.options.routeColor,'#ff0000');assert.equal(restored.preferences.options.routeWidthMm,2.5);assert.equal(restored.preferences.options.routeHeightMm,1.5);
  await reopened.close();
  const report={passed:true,colorWheel:true,rgb:true,brightness:true,keyboard:true,widthMm:2.5,generatedHeightMm:2.4,restoredHeightMm:1.5,colorUpdates3D:true,colorKeepsStl:true,validation:preview.report.validation,errors};
  await writeFile(join(output,'result.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report));
  await manager.close();window.destroy();app.exit(0);
}
run().catch(async error=>{console.error(error);await writeFile(join(output,'failure.txt'),error.stack||String(error));if(window)await writeFile(join(output,'failure.png'),(await window.webContents.capturePage()).toPNG());await manager?.close();window?.destroy();app.exit(1);});
